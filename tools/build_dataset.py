#!/usr/bin/env python3
"""Merge curated content + the frequency deck into the files the app loads.

Reads:
  content/nouns/*.json      themed noun lists        -> production cards
  content/verbs/*.json      verb lists + principal parts
  content/grammar/*.json    grammar points with cloze items
  data/vocab_frequency.json  generated by build_vocab.py (optional)

Enriches curated words with gender/plural (german-nouns) and a real example
sentence (Tatoeba), then writes:

  data/items.json        flat array of every study item
  data/items/<level>.json  the same items split per level (lazy-loaded by the app)
  data/levels.json       level -> group -> item-id structure
  data/attribution.json  credits for CC-BY sentences actually used
"""

from __future__ import annotations

import json
import re
import sys
from pathlib import Path

from common import (
    ROOT,
    build_sentence_index,
    build_sentence_index_multi,
    find_example,
    find_examples,
    load_nouns,
    load_sentence_pairs,
)
from mnemonic import gender_mnemonic

LEVEL_ORDER = ["a1", "a2", "b1", "b2", "c1", "c2"]
LEVEL_META = {
    "a1": "Beginner",
    "a2": "Elementary",
    "b1": "Intermediate",
    "b2": "Upper intermediate",
    "c1": "Advanced",
    "c2": "Mastery",
}

# definite-article forms per case for the case drill track (#79)
CASE_LABELS = {"akk": "Akkusativ", "dat": "Dativ", "gen": "Genitiv"}
CASE_FORMS = {
    "der": {"akk": "den", "dat": "dem", "gen": "des"},
    "die": {"akk": "die", "dat": "der", "gen": "der"},
    "das": {"akk": "das", "dat": "dem", "gen": "des"},
}


def slug(text: str) -> str:
    text = text.lower()
    text = (
        text.replace("ä", "ae").replace("ö", "oe").replace("ü", "ue").replace("ß", "ss")
    )
    return re.sub(r"[^a-z0-9]+", "-", text).strip("-")


def plural_surface(plural: str) -> str:
    parts = plural.split(" ", 1)
    return parts[1] if len(parts) == 2 else plural


def load_content(kind: str) -> list[dict]:
    """All content/<kind>/*.json files, sorted by filename."""
    files = sorted((ROOT / "content" / kind).glob("*.json"))
    out = []
    for path in files:
        out.append(json.loads(path.read_text(encoding="utf-8")))
    return out


def main() -> int:
    nouns = load_nouns()
    pairs = load_sentence_pairs()
    index = build_sentence_index(pairs) if pairs else {}
    multi = build_sentence_index_multi(pairs) if pairs else {}

    conj_path = ROOT / "data" / "conjugations.json"
    conjugations = json.loads(conj_path.read_text(encoding="utf-8")) if conj_path.exists() else {}

    items: list[dict] = []
    levels: dict[str, dict] = {lvl: {"id": lvl, "name": lvl.upper(), "title": LEVEL_META[lvl], "groups": []} for lvl in LEVEL_ORDER}
    used_attribution: set[str] = set()

    def add_group(level: str, group_id: str, name: str, kind: str, intro: str, subtitle: str = "") -> dict:
        g = {"id": group_id, "name": name, "subtitle": subtitle, "kind": kind, "intro": intro, "items": []}
        levels[level]["groups"].append(g)
        return g

    group_cache: dict[str, dict] = {}

    def ensure_group(level: str, group_id: str, name: str, kind: str, intro: str) -> dict:
        if group_id not in group_cache:
            group_cache[group_id] = add_group(level, group_id, name, kind, intro)
        return group_cache[group_id]

    # --- curated nouns -> production cards -------------------------------
    for doc in load_content("nouns"):
        level = doc["level"]
        for grp in doc["groups"]:
            gid = f"{level}-{grp['id']}"
            group = add_group(level, gid, grp["name"], "noun", grp.get("intro", ""))
            for word, english in grp["words"]:
                noun = nouns.get(word)
                article = noun.article if noun else ""
                plural = noun.plural if noun else ""
                hit = find_example(index, word, [plural_surface(plural)]) if index else None
                de = f"{article} {word}".strip()
                item = {
                    "id": f"{gid}-{slug(word)}",
                    "level": level,
                    "group": gid,
                    "groupName": grp["name"],
                    "kind": "noun",
                    "intro": grp.get("intro", ""),
                    "de": de,
                    "en": english,
                    "plural": plural,
                    "sentence_de": hit[0] if hit else "",
                    "sentence_en": hit[1] if hit else "",
                    "note": grp.get("notes", {}).get(word, ""),
                }
                if hit and hit[2]:
                    item["attribution"] = hit[2]
                    used_attribution.add(hit[2])
                group["items"].append(item["id"])
                items.append(item)

                # separate SRS tracks: article (gender) and plural
                if article:
                    gg = ensure_group(
                        level,
                        f"{level}-gender",
                        "Article (der/die/das)",
                        "gender",
                        "Type the correct article for each noun.",
                    )
                    gitem = {
                        "id": f"{level}-gender-{slug(word)}",
                        "level": level,
                        "group": gg["id"],
                        "groupName": gg["name"],
                        "kind": "gender",
                        "prompt": word,
                        "answer": article,
                        "de": f"{article} {word}",
                        "en": english,
                        "note": grp.get("notes", {}).get(word, ""),
                    }
                    gg["items"].append(gitem["id"])
                    items.append(gitem)
                # separate SRS track: definite-article case forms (#79)
                if article and article in CASE_FORMS:
                    cg = ensure_group(
                        level,
                        f"{level}-case",
                        "Case forms",
                        "case",
                        "Type the definite article in the given case (Akkusativ, Dativ, Genitiv).",
                    )
                    for case_key, case_label in CASE_LABELS.items():
                        form = CASE_FORMS[article][case_key]
                        cid = f"{level}-case-{slug(word)}-{case_key}"
                        cg["items"].append(cid)
                        items.append(
                            {
                                "id": cid,
                                "level": level,
                                "group": cg["id"],
                                "groupName": cg["name"],
                                "kind": "case",
                                "prompt": f"{article} {word} — {case_label}",
                                "answer": form,
                                "de": form,
                                "en": english,
                                "note": grp.get("notes", {}).get(word, ""),
                            }
                        )
                if plural:
                    pg = ensure_group(
                        level,
                        f"{level}-plural",
                        "Plural forms",
                        "plural",
                        "Type the plural form (with its article).",
                    )
                    pitem = {
                        "id": f"{level}-plural-{slug(word)}",
                        "level": level,
                        "group": pg["id"],
                        "groupName": pg["name"],
                        "kind": "plural",
                        "prompt": f"{article} {word}".strip(),
                        "answer": plural,
                        "de": plural,
                        "en": english,
                    }
                    pg["items"].append(pitem["id"])
                    items.append(pitem)

    # --- curated verbs -> production cards --------------------------------
    for doc in load_content("verbs"):
        level = doc["level"]
        for grp in doc["groups"]:
            gid = f"{level}-{grp['id']}"
            group = add_group(level, gid, grp["name"], "verb", grp.get("intro", ""))
            for entry in grp["words"]:
                word, english, forms = entry[0], entry[1], entry[2]
                ex_de = entry[3] if len(entry) > 3 else ""
                ex_en = entry[4] if len(entry) > 4 else ""
                hit = find_example(index, word) if index else None
                if ex_de:
                    sentence_de, sentence_en, attr = ex_de, ex_en, ""
                elif hit:
                    sentence_de, sentence_en, attr = hit
                else:
                    sentence_de, sentence_en, attr = "", "", ""
                item = {
                    "id": f"{gid}-{slug(word)}",
                    "level": level,
                    "group": gid,
                    "groupName": grp["name"],
                    "kind": "verb",
                    "intro": grp.get("intro", ""),
                    "de": word,
                    "en": english,
                    "forms": forms,
                    "sentence_de": sentence_de,
                    "sentence_en": sentence_en,
                    "note": grp.get("notes", {}).get(word, ""),
                }
                if attr:
                    item["attribution"] = attr
                    used_attribution.add(attr)
                base = word.replace("sich ", "").strip()
                if base in conjugations:
                    item["conjugation"] = conjugations[base]
                group["items"].append(item["id"])
                items.append(item)

    # --- curated grammar -> cloze cards -----------------------------------
    for doc in load_content("grammar"):
        level = doc["level"]
        for grp in doc["groups"]:
            gid = f"{level}-{grp['id']}"
            group = add_group(level, gid, grp["name"], "cloze", grp.get("intro", ""), grp.get("subtitle", ""))
            for i, it in enumerate(grp["items"], start=1):
                item = {
                    "id": f"{gid}-{i}",
                    "level": level,
                    "group": gid,
                    "groupName": grp["name"],
                    "kind": "cloze",
                    "intro": grp.get("intro", ""),
                    "prompt": it["p"],
                    "answer": it["a"],
                    "alt": it.get("alt", []),
                    "en": it.get("en", ""),
                    "hint": it.get("hint", ""),
                    "note": it.get("note", ""),
                }
                group["items"].append(item["id"])
                items.append(item)

    # --- generated / imported vocab decks ---------------------------------
    for extra in ("vocab_frequency.json", "vocab_personal.json"):
        extra_path = ROOT / "data" / extra
        if not extra_path.exists():
            continue
        extra_items = json.loads(extra_path.read_text(encoding="utf-8"))
        groups: dict[str, dict] = {}
        tracks = 0
        for it in extra_items:
            gid = it["group"]
            if gid not in groups:
                groups[gid] = add_group(
                    it["level"], gid, it["groupName"], it.get("kind", "cloze"), it.get("intro", "")
                )
            groups[gid]["items"].append(it["id"])
            items.append(it)
            if it.get("attribution"):
                used_attribution.add(it["attribution"])

            # separate SRS tracks for every noun with a known article/plural (#78)
            if it.get("kind") == "noun":
                parts = (it.get("de") or "").split(" ", 1)
                if len(parts) == 2 and parts[0] in ("der", "die", "das"):
                    article, word = parts[0], parts[1]
                    level, en = it["level"], it.get("en", "")
                    gg = ensure_group(
                        level,
                        f"{level}-core-gender",
                        "Core nouns: gender",
                        "gender",
                        "Type the article (der/die/das) for each core noun.",
                    )
                    gg["items"].append(f"{it['id']}-gender")
                    items.append(
                        {
                            "id": f"{it['id']}-gender",
                            "level": level,
                            "group": gg["id"],
                            "groupName": gg["name"],
                            "kind": "gender",
                            "prompt": word,
                            "answer": article,
                            "de": it["de"],
                            "en": en,
                        }
                    )
                    tracks += 1
                    if it.get("plural"):
                        pg = ensure_group(
                            level,
                            f"{level}-core-plural",
                            "Core nouns: plural",
                            "plural",
                            "Type the plural form (with its article) for each core noun.",
                        )
                        pg["items"].append(f"{it['id']}-plural")
                        items.append(
                            {
                                "id": f"{it['id']}-plural",
                                "level": level,
                                "group": pg["id"],
                                "groupName": pg["name"],
                                "kind": "plural",
                                "prompt": it["de"],
                                "answer": it["plural"],
                                "de": it["plural"],
                                "en": en,
                            }
                        )
                        tracks += 1
        print(f"{extra}: {len(extra_items):,} items, +{tracks:,} gender/plural tracks")

    # --- multiple example sentences per vocabulary item (#131) -----------
    if multi:
        with_examples = 0
        for it in items:
            if it.get("kind") not in ("noun", "verb", "adj"):
                continue
            de = it.get("de") or ""
            if it["kind"] == "noun":
                word = de.split(" ", 1)[1] if " " in de else de
                extra = [it["plural"].split(" ", 1)[-1]] if it.get("plural") else []
            else:
                word, extra = de, []
            ex: list[dict] = []
            if it.get("sentence_de"):
                ex.append({"de": it["sentence_de"], "en": it.get("sentence_en", "")})
            for d, e, _a in find_examples(multi, word, extra, limit=3):
                if all(x["de"] != d for x in ex):
                    ex.append({"de": d, "en": e})
            if ex:
                it["examples"] = ex[:3]
                with_examples += 1
        print(f"examples attached to {with_examples:,} vocabulary items")

    # --- vocabulary cloze track: type the word into a sentence (#131) -----
    cloze_added = 0
    for it in list(items):
        if it.get("kind") not in ("noun", "verb", "adj"):
            continue
        de = it.get("de") or ""
        answer = de.split(" ", 1)[1] if (it["kind"] == "noun" and " " in de) else de
        if not answer:
            continue
        usable = [
            ex
            for ex in it.get("examples", [])
            if re.search(r"\b" + re.escape(answer) + r"\b", ex["de"])
        ]
        if not usable:
            continue
        level = it["level"]
        auto = it["id"].startswith("freq-")
        g = ensure_group(
            level,
            f"{level}-core-cloze" if auto else f"{level}-vocab-cloze",
            "Core vocab: cloze" if auto else "Vocabulary cloze",
            "vocab-cloze",
            "Type the missing word into the sentence.",
        )
        cid = f"{it['id']}-cloze"
        g["items"].append(cid)
        items.append(
            {
                "id": cid,
                "level": level,
                "group": g["id"],
                "groupName": g["name"],
                "kind": "vocab-cloze",
                "answer": answer,
                "de": de,
                "en": it.get("en", ""),
                "hint": it.get("en", ""),
                "examples": usable,
            }
        )
        cloze_added += 1
    print(f"vocab-cloze items: {cloze_added:,}")

    # --- gender mnemonics for every noun ----------------------------------
    for it in items:
        if it.get("kind") == "noun":
            parts = (it.get("de") or "").split(" ")
            if len(parts) > 1 and parts[0] in ("der", "die", "das"):
                it["mnemonic"] = gender_mnemonic(parts[1], parts[0])

    # --- attach conjugations to every verb that has one (#80) -------------
    conj_attached = 0
    for it in items:
        if it.get("kind") == "verb" and "conjugation" not in it:
            base = (it.get("de") or "").replace("sich ", "").strip()
            if base in conjugations:
                it["conjugation"] = conjugations[base]
                conj_attached += 1
    if conj_attached:
        print(f"conjugations attached to {conj_attached:,} deck verbs")

    # --- backfill missing IPA from the Wiktionary extract (#81) -----------
    ipa_path = ROOT / "data" / "ipa.json"
    if ipa_path.exists():
        ipa_map = json.loads(ipa_path.read_text(encoding="utf-8"))
        filled = 0
        for it in items:
            if it.get("kind") in ("noun", "verb", "adj") and not it.get("ipa"):
                de = it.get("de") or ""
                word = de.split(" ", 1)[1] if (it["kind"] == "noun" and " " in de) else de
                base = word.replace("sich ", "").strip()
                if base in ipa_map:
                    it["ipa"] = ipa_map[base]
                    filled += 1
        print(f"IPA backfilled for {filled:,} items")

    # --- curated overrides (id -> partial item) ---------------------------
    overrides_path = ROOT / "content" / "overrides.json"
    if overrides_path.exists():
        overrides = json.loads(overrides_path.read_text(encoding="utf-8"))
        applied = 0
        for it in items:
            patch = overrides.get(it["id"])
            if patch:
                it.update(patch)
                applied += 1
        print(f"overrides applied: {applied}")

    # --- reading passages -------------------------------------------------
    passages: list[dict] = []
    for path in sorted((ROOT / "content" / "reading").glob("*.json")):
        doc = json.loads(path.read_text(encoding="utf-8"))
        for p in doc.get("passages", []):
            p["level"] = doc["level"]
            passages.append(p)
    (ROOT / "data" / "reading.json").write_text(
        json.dumps(passages, ensure_ascii=False, indent=1), encoding="utf-8"
    )

    # --- write outputs ----------------------------------------------------
    levels_out = [levels[lvl] for lvl in LEVEL_ORDER if levels[lvl]["groups"]]
    data_dir = ROOT / "data"
    data_dir.mkdir(parents=True, exist_ok=True)
    (data_dir / "items.json").write_text(
        json.dumps(items, ensure_ascii=False), encoding="utf-8"
    )
    (data_dir / "levels.json").write_text(
        json.dumps(levels_out, ensure_ascii=False, indent=1), encoding="utf-8"
    )

    # Per-level split so the app can load the deck on demand (issue #102).
    items_dir = data_dir / "items"
    items_dir.mkdir(exist_ok=True)
    for stale in items_dir.glob("*.json"):
        stale.unlink()
    by_level: dict[str, list[dict]] = {lvl: [] for lvl in LEVEL_ORDER}
    for it in items:
        by_level.setdefault(it["level"], []).append(it)
    for lvl, arr in by_level.items():
        if arr:
            (items_dir / f"{lvl}.json").write_text(
                json.dumps(arr, ensure_ascii=False), encoding="utf-8"
            )
    (data_dir / "attribution.json").write_text(
        json.dumps(sorted(used_attribution), ensure_ascii=False, indent=1),
        encoding="utf-8",
    )

    print(f"wrote {len(items):,} items across {len(levels_out)} levels")
    for lvl in levels_out:
        n = sum(len(g["items"]) for g in lvl["groups"])
        print(f"  {lvl['id'].upper()}: {n:>5} items, {len(lvl['groups'])} groups")
    return 0


if __name__ == "__main__":
    sys.exit(main())
