export function t(lang: Lang, key: string, params?: Record<string, string | number>): string {
  let s = MESSAGES[lang]?.[key] ?? MESSAGES.en[key] ?? key;
  if (params) {
    for (const [k, v] of Object.entries(params)) s = s.split(`{${k}}`).join(String(v));
  }
  return s;
}
